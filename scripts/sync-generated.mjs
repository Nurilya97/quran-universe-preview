import fs from 'node:fs'
import path from 'node:path'
import { ROOT_DEMOS, FORMS } from '../src/demo.js'
import { AYAH_PROTOTYPES } from '../src/ayahPrototype.js'
import { PILOT_SOURCE_ADAPTERS } from '../src/data/sourceAdapters.js'
import { QURAN_UNIVERSE_DATA_VERSION } from '../src/data/quranUniverseData.js'

const root = process.cwd()
const check = process.argv.includes('--check')
const readJson = p => JSON.parse(fs.readFileSync(path.join(root, p), 'utf8'))
const rootRegistry = readJson('src/data/research/rootRegistry.json')
const sourceRegistry = readJson('src/data/research/sourceRegistry.json')
const roadmap = readJson('src/data/research/roadmap.json')

const esc = value => String(value ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ')

const roadmapMd = `# Quran Universe roadmap

Generated from \`src/data/research/roadmap.json\`. Do not edit this file directly.

| # | Phase | Status | Priority | Current deliverable / next action |
|---:|---|---|---|---|
${roadmap.phases.map(item => `| ${item.order} | ${esc(item.phase)} | ${esc(item.status)} | ${esc(item.priority)} | ${esc(item.deliverable)}<br>**Next:** ${esc(item.nextAction)} |`).join('\n')}

## Operational rule

Runtime/data truth is the code and structured records in this repository. No Notion or second repository is required.
`

const sourcesMd = `# Sources & licenses

Generated from \`src/data/research/sourceRegistry.json\`. Do not edit this file directly.

| Source | Layers | Legal | Commercial | License | Last checked |
|---|---|---|---|---|---|
${sourceRegistry.sources.map(item => `| ${esc(item.source)} | ${esc((item.layer || []).join(', '))} | ${esc(item.legalStatus)} | ${esc(item.commercialUse)} | ${esc(item.license)} | ${esc(item.lastChecked)} |`).join('\n')}

Detailed URLs, next actions, modification rules, cost and rationale live in the JSON registry.
`

const rootsMd = `# Root registry

Generated from \`src/data/research/rootRegistry.json\`. Do not edit this file directly.

| Root | Status | Phase | Model | Human reviewed | Scholar reviewed | Updated | Next action |
|---|---|---|---|---|---|---|---|
${rootRegistry.roots.map(item => `| ${esc(item.root)} | ${esc(item.status)} | ${esc(item.phase)} | ${esc(item.modelVersion || '—')} | ${item.humanReviewed ? 'yes' : 'no'} | ${item.scholarReviewed ? 'yes' : 'no'} | ${esc(item.updated)} | ${esc(item.nextAction)} |`).join('\n')}
`

const visibleForms = FORMS.filter(form => !form.relatedOnly)
const statusMd = `# Quran Universe system status

Generated from canonical project data. Do not edit this file directly.

- Data layer: **${QURAN_UNIVERSE_DATA_VERSION}**
- Product roots: **${Object.keys(ROOT_DEMOS).length}** (${Object.values(ROOT_DEMOS).map(root => root.arabic).join(' · ')})
- Research registry roots: **${rootRegistry.roots.length}**
- Registered forms: **${FORMS.length}** total / **${visibleForms.length}** visible
- Ayah Space records: **${Object.keys(AYAH_PROTOTYPES).length}** (${Object.keys(AYAH_PROTOTYPES).join(', ')})
- External pilot adapters: ${Object.entries(PILOT_SOURCE_ADAPTERS).map(([id, value]) => `**${id}**=${value.pilotStatus}`).join(' · ')}
- Authority: **single repository**
- Notion dependency: **none**
- Legacy runtime dependency: **none**

## Automatic gates

1. \`npm run sync:check\` — generated documentation matches canonical JSON.
2. \`npm run audit:system\` — architecture, skills, registries and workflows remain coherent.
3. \`npm run test:content\` — Quran/content invariants.
4. production build.
5. Playwright approved-UI contracts before Pages deployment.
6. weekly system-health + upstream/source freshness watch.
`

const outputs = new Map([
  ['docs/ROADMAP.md', roadmapMd],
  ['docs/SOURCES_AND_LICENSES.md', sourcesMd],
  ['docs/ROOT_REGISTRY.md', rootsMd],
  ['docs/SYSTEM_STATUS.md', statusMd],
])

let drift = false
for (const [relative, content] of outputs) {
  const full = path.join(root, relative)
  const current = fs.existsSync(full) ? fs.readFileSync(full, 'utf8') : ''
  if (current !== content) {
    drift = true
    if (check) console.error('GENERATED_DOC_DRIFT:', relative)
    else {
      fs.mkdirSync(path.dirname(full), { recursive: true })
      fs.writeFileSync(full, content)
      console.log('SYNCED:', relative)
    }
  }
}
if (check && drift) process.exit(1)
if (check) console.log('Generated documentation is synchronized.')
